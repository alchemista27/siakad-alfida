import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const path = resolve(root, "src/components/attendance/unit-work-schedule-panel.tsx");
assert.ok(existsSync(path), "unit schedule panel must exist");
const panel = readFileSync(path, "utf8");
const duty = readFileSync(resolve(root, "src/components/attendance/workday-management-panel.tsx"), "utf8");
assert.match(panel, /\/api\/attendance\/work-schedules\?unitId=/);
assert.match(panel, /\/api\/attendance\/work-schedules\/\$\{unitId\}\/\$\{weekday\}/);
assert.match(panel, /startTime|lateGraceMinutes|endTime|overtimeStartTime/);
assert.match(panel, /Tidak wajib presensi kecuali piket khusus/);
assert.match(panel, /Belum dikonfigurasi/);
assert.match(panel, /role="alert"|role=\{[^}]+"alert"/);
assert.match(panel, /AbortController/);
assert.match(duty, /startTime: dutyForm\.startTime, lateGraceMinutes: Number\(dutyForm\.lateGraceMinutes\), endTime: dutyForm\.endTime, overtimeStartTime: dutyForm\.overtimeStartTime/);
assert.match(duty, /Jam piket belum diatur/);
assert.match(duty, /UnitWorkSchedulePanel/);
console.log("work schedule UI passed");
