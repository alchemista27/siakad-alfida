import assert from "node:assert/strict";
import { existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";
const root = resolve(import.meta.dirname, "..");
const path = resolve(root, "src/components/organization/employee-suggestion-picker.tsx");
assert.ok(existsSync(path), "shared employee suggestion picker must exist");
const picker = readFileSync(path, "utf8");
const unit = readFileSync(resolve(root, "src/components/organization/unit-admin-modal.tsx"), "utf8");
const department = readFileSync(resolve(root, "src/components/organization/department-admin-modal.tsx"), "utf8");
const page = readFileSync(resolve(root, "src/app/page.tsx"), "utf8");
assert.match(picker, /query\.trim\(\)\.length\s*<\s*1/, "suggestions must start at one character");
assert.match(picker, /\/api\/employees\/suggestions\?\$\{params\.toString\(\)\}/);
assert.match(picker, /params\.set\("unitId", unitId\)/, "scoped unit admins must pass their unit to the API");
assert.match(unit, /EmployeeSuggestionPicker[^>]*unitId=\{unit\.id\}/);
assert.match(picker, /setTimeout\([\s\S]*?200/);
assert.match(picker, /AbortController|controller\.abort\(\)/);
assert.match(picker, /response\.ok/);
assert.match(picker, /role="listbox"/);
assert.match(picker, /role="option"/);
assert.match(picker, /ArrowDown|ArrowUp|Enter|Escape/);
assert.match(picker, /role="alert"/);
assert.match(picker, /Memuat|Tidak ada pegawai/);
assert.match(picker, /onSelect\(employee\)/, "click or Enter must select the returned employee object");
assert.match(picker, /onSelect\(null\)/, "editing search must invalidate a previous selection");
assert.match(picker, /aria-autocomplete="list"/);
assert.match(picker, /aria-activedescendant/);
assert.match(picker, /aria-selected/);
assert.match(picker, /aria-live=|role="status"/, "loading and empty feedback must be announced");
assert.match(picker, /controller\.signal\.aborted/, "stale responses must not replace fresh results");
assert.match(picker, /payload\.every\(/, "malformed suggestion rows must show an error, never become selectable IDs");
assert.match(picker, /onBlur=\{/, "leaving the combobox must close its suggestion popup");
assert.match(picker, /aria-describedby=\{/, "feedback must be associated with the search input");
for (const [name, modal] of [["unit", unit], ["department", department]] as const) {
  assert.match(modal, /EmployeeSuggestionPicker/, `${name} modal must use the shared picker`);
  assert.doesNotMatch(modal, /employees\.filter\(|activeEmployees|<select required value=\{userId\}/, `${name} modal must not filter prefetched employees`);
  assert.match(modal, /EmployeeSuggestionPicker[^>]*selected=\{selectedEmployee\}[^>]*onSelect=\{setSelectedEmployee\}/, `${name} modal must bind selection to the shared picker`);
  assert.match(modal, /userId:\s*selectedEmployee\.id/, `${name} modal must POST the selected ID rather than raw query`);
  assert.match(modal, /disabled=\{[^}]*!selectedEmployee/, `${name} modal must block submit without a selection`);
  assert.match(modal, /setSelectedEmployee\(null\)/, `${name} modal must clear selection on success or scope change`);
}
assert.doesNotMatch(page, /<UnitAdminModal[^>]*employees=|<DepartmentAdminModal[^>]*employees=/);
console.log("employee suggestions UI passed");
