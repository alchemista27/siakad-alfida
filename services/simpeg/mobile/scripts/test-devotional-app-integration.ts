import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { resolve } from "node:path";

const app = readFileSync(resolve(__dirname, "../App.tsx"), "utf8");

assert.match(app, /type MobilePage = "attendance" \| "calendar" \| "prayer" \| "almatsurat" \| "profile"/);
assert.match(app, /useState<MobilePage>\("attendance"\)/, "Attendance must remain the first authenticated page");
assert.match(app, /<Modal[^>]+visible=\{sidebarOpen\}/, "Authenticated navigation must use a native sidebar drawer");
assert.match(app, /setActivePage\(item\.id\)/, "Each sidebar item must navigate without stacking page content");
assert.match(app, /activePage === "calendar"[\s\S]*?<HijriCalendarCard/, "Calendar must have its own page");
assert.match(app, /activePage === "prayer"[\s\S]*?<PrayerTimesCard/, "Prayer schedule must have its own page");
assert.match(app, /activePage === "almatsurat"[\s\S]*?<AlmatsuratCard/, "Al-Ma'tsurat must have its own page");
assert.match(app, /sidebarLabel: "Kalender Hijriyah"/);
assert.match(app, /sidebarLabel: "Jadwal Salat"/);
assert.match(app, /sidebarLabel: "Al-Ma’tsurat"/);
assert.match(app, /sidebarLabel: "Profil"/);
assert.match(app, /activePage === "profile"[\s\S]*?<ProfilePage/);
assert.match(app, /validatePrayerLocation\(position, Date\.now\(\)/);
assert.match(app, /Location\.requestForegroundPermissionsAsync\(\)/);
assert.match(app, /AppState\.addEventListener/);
assert.match(app, /prayerRequestVersion = useRef\(0\)/);
assert.match(app, /const requestVersion = \+\+prayerRequestVersion\.current/);
assert.match(app, /requestVersion !== prayerRequestVersion\.current/);
assert.match(app, /prayerRequestVersion\.current \+= 1/);
assert.match(app, /NativeStatusBar\.currentHeight/);
assert.match(app, /minHeight:\s*44/);
assert.match(app, /minWidth:\s*44/);
assert.match(app, /accessibilityLabel="Buka menu"/);
assert.doesNotMatch(app, /requestBackgroundPermissionsAsync|startLocationUpdatesAsync/);
console.log("devotional sidebar navigation contract passed");
